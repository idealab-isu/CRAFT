def _safe_float(val) -> Optional[float]:
    """Parse a field value to float."""
    if val is None:
        return None
    val = str(val).strip().strip('"').strip("'")
    try:
        return float(eval(val))
    except Exception:
        try:
            return float(val)
        except (ValueError, TypeError):
            return None


def _match_ball_bearing(prompt_dims: Dict, comp: Dict) -> Tuple[float, Dict]:
    """Match ball bearing: fv[1]=bore, fv[2]=od, fv[3]=width, fv[7]=flange_dia."""
    fv = comp.get("field_values", [])
    if len(fv) < 4:
        return float('inf'), {}

    comp_dims = {}
    bore = _safe_float(fv[1])
    od = _safe_float(fv[2])
    width = _safe_float(fv[3])
    flange = _safe_float(fv[7]) if len(fv) > 7 else None

    if bore is not None:
        comp_dims['bore'] = bore
    if od is not None:
        comp_dims['od'] = od
    if width is not None:
        comp_dims['width'] = width
    if flange and flange > 0:
        comp_dims['flange_dia'] = flange

    return _compute_dimension_error(prompt_dims, comp_dims), comp_dims


