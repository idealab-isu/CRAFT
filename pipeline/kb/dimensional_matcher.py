def _extract_numbers_with_labels(text: str) -> Dict[str, float]:
    """Extract labeled numeric dimensions from a prompt."""
    dims = {}

    # Common patterns: "Xmm bore", "X mm outer diameter", etc.
    patterns = [
        (r'([\d.]+)\s*mm\s*bore', 'bore'),
        (r'([\d.]+)\s*mm\s*outer\s*diameter', 'od'),
        (r'([\d.]+)\s*mm\s*(?:inner\s*)?(?:hole|inner\s*diameter)', 'bore'),
        (r'([\d.]+)\s*mm\s*width', 'width'),
        (r'([\d.]+)\s*mm\s*thick(?:ness)?', 'thickness'),
        (r'([\d.]+)\s*mm\s*flange\s*diameter', 'flange_dia'),
        (r'([\d.]+)\s*mm\s*face\s*width', 'face_width'),
        (r'([\d.]+)\s*mm\s*body\s*length', 'body_length'),
        (r'([\d.]+)\s*mm\s*(?:diameter\s*)?shaft', 'shaft_dia'),
        (r'([\d.]+)\s*mm\s*mounting\s*hole\s*spacing', 'hole_spacing'),
        (r'([\d.]+)\s*mm\s*(?:across\s*flats)', 'across_flats'),
        (r'for\s*([\d.]+)\s*mm\s*screws', 'screw_dia'),
        (r'([\d.]+)\s*mm\s*thread', 'screw_dia'),
        (r'([\d.]+)\s*mm\s*head\s*diameter', 'head_dia'),
        (r'head\s*height\s*([\d.]+)\s*mm', 'head_height'),
        (r'([\d.]+)\s*mm\s*diameter', 'diameter'),
        (r'([\d.]+)\s*mm\s*stator\s*diameter', 'stator_dia'),
        (r'([\d.]+)\s*mm\s*height', 'height'),
        (r'([\d.]+)\s*mm\s*length', 'length'),
        (r'([\d.]+)\s*mm\s*long', 'length'),
        (r'([\d.]+)\s*mm\s*tall', 'height'),
        (r'([\d.]+)\s*mm\s*wide', 'rail_width'),
        (r'([\d.]+)\s*mm\s*barrel\s*diameter', 'barrel_dia'),
        (r'([\d.]+)\s*mm\s*total\s*length', 'total_length'),
        (r'([\d.]+)\s*mm\s*body\s*diameter', 'body_dia'),
        (r'([\d.]+)\s*mm\s*pitch\s*diameter', 'pitch_dia'),
        (r'(\d+)\s*teeth', 'teeth'),
        (r'for\s*([\d.]+)\s*mm\s*(?:shaft|rod)', 'shaft_dia'),
        # LED-specific: "5mm through-hole LED" or "A 5.0mm through-hole LED"
        (r'([\d.]+)\s*mm\s*through-hole\s*led', 'led_dia'),
        (r'([\d.]+)\s*mm\s*led', 'led_dia'),
    ]

    for pattern, label in patterns:
        m = re.search(pattern, text, re.IGNORECASE)
        if m:
            try:
                dims[label] = float(m.group(1))
            except ValueError:
                pass

    # AxB pattern: "40mm x 40mm x 9.5mm" or "40.0mm x 40.0mm"
    axb = re.findall(r'([\d.]+)\s*mm\s*x\s*([\d.]+)\s*mm(?:\s*x\s*([\d.]+)\s*mm)?', text, re.IGNORECASE)
    if axb:
        dims['dim_x'] = float(axb[0][0])
        dims['dim_y'] = float(axb[0][1])
        if axb[0][2]:
            dims['dim_z'] = float(axb[0][2])

    # Block size pattern: "block size 40mm x 35mm"
    block = re.search(r'block\s*size\s*([\d.]+)\s*mm\s*x\s*([\d.]+)\s*mm', text, re.IGNORECASE)
    if block:
        dims['block_length'] = float(block.group(1))
        dims['block_width'] = float(block.group(2))

    return dims


