def match_and_get_scad(prompt: str) -> Optional[str]:
    """
    Match a prompt and return the OpenSCAD code if confident.

    Args:
        prompt: Natural language prompt

    Returns:
        OpenSCAD code string or None
    """
    result = match_prompt_to_component(prompt)
    if result.has_match:
        return result.get_scad_code()
    return None


def get_type_constant(prompt: str) -> Optional[str]:
    """
    Match a prompt and return just the type constant name.

    Args:
        prompt: Natural language prompt

    Returns:
        Type constant string (e.g., "BB608") or None
    """
    result = match_prompt_to_component(prompt)
    if result.has_match:
        return result.best_match.type_constant
    return None
