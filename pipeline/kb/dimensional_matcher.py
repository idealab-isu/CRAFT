"""
Dimensional Matcher for NopSCADlib Components

Extracts numeric dimensions from natural language prompts and matches them
against the NopSCADlib component catalog to find the exact type constant.

This is the reverse of generate_prompts.py: instead of converting
field_values → prompt, it converts prompt → field_values → type_constant.

Example:
    Prompt: "A ball bearing with 8mm bore, 22mm outer diameter, and 7mm width"
    Extracted: {bore: 8.0, od: 22.0, width: 7.0}
    Matched:   BB608 (bore=8, od=22, width=7) → confidence=0.99
"""

import re
import json
from pathlib import Path
from dataclasses import dataclass, field
from typing import List, Dict, Optional, Tuple

# Path to the benchmark catalog (generated by enumerate_nopscadlib.py)
_CATALOG_PATHS = [
    Path(__file__).parent.parent.parent / "Text2CAD_SPM_2026" / "benchmark_ground_truth.json",
    Path(__file__).parent.parent.parent / "Text2CAD_SPM_2026" / "nopscadlib_component_catalog.json",
]


@dataclass
class DimensionalMatch:
    """Result of dimensional matching for a single component."""
    component_id: str           # e.g. "ball_bearing__BB608"
    type_constant: str          # e.g. "BB608"
    component_family: str       # e.g. "ball_bearing"
    module_function: str        # e.g. "ball_bearing"
    scad_call: str              # e.g. "ball_bearing(BB608);"
    confidence: float           # 0.0 to 1.0
    dimension_error: float      # Euclidean distance in dimension space
    matched_dimensions: Dict[str, float] = field(default_factory=dict)
    prompt_dimensions: Dict[str, float] = field(default_factory=dict)


@dataclass
class DimensionalMatchResult:
    """Result of dimensional matching on a prompt."""
    original_prompt: str
    detected_family: Optional[str] = None
    matches: List[DimensionalMatch] = field(default_factory=list)
    best_match: Optional[DimensionalMatch] = None
    has_match: bool = False

    def get_scad_code(self) -> Optional[str]:
        """Get OpenSCAD code for the best match."""
        if self.best_match:
            return (
                f"include <NopSCADlib/lib.scad>\n\n"
                f"{self.best_match.scad_call}"
            )
        return None


# =============================================================================
# CATALOG LOADER
# =============================================================================

_catalog_cache: Optional[Dict] = None


def _load_catalog() -> Dict:
    """Load the NopSCADlib component catalog (cached)."""
    global _catalog_cache
    if _catalog_cache is not None:
        return _catalog_cache

    for path in _CATALOG_PATHS:
        if path.exists():
            with open(path) as f:
                data = json.load(f)
            # benchmark_ground_truth.json has "components" list
            if "components" in data:
                _catalog_cache = data
                return _catalog_cache
            # nopscadlib_component_catalog.json has "families_summary" + individual entries
            if "families_summary" in data:
                _catalog_cache = data
                return _catalog_cache

    _catalog_cache = {"components": []}
    return _catalog_cache


def _get_components_by_family(family: str) -> List[Dict]:
    """Get all components in a family from the catalog."""
    catalog = _load_catalog()
    components = catalog.get("components", [])
    return [c for c in components if c.get("component_family") == family]


