def _compute_dimension_error(prompt_dims: Dict[str, float], comp_dims: Dict[str, float]) -> float:
    """
    Compute Euclidean distance between prompt dimensions and component dimensions.
    Only compares dimensions that appear in BOTH sets.
    Returns infinity if no overlap.
    """
    # Find common dimension keys
    common_keys = set(prompt_dims.keys()) & set(comp_dims.keys())
    if not common_keys:
        return float('inf')

    # Compute relative error for each common dimension
    errors = []
    for key in common_keys:
        p_val = prompt_dims[key]
        c_val = comp_dims[key]
        if c_val == 0 and p_val == 0:
            errors.append(0.0)
        elif c_val == 0:
            errors.append(abs(p_val))
        else:
            # Relative error
            errors.append(abs(p_val - c_val) / max(abs(c_val), 1e-6))

    if not errors:
        return float('inf')

    # Return mean relative error
    return sum(errors) / len(errors)


def _error_to_confidence(error: float, n_matched: int, n_total_prompt: int) -> float:
    """
    Convert dimension error to confidence score.

    Args:
        error: Mean relative error (0 = perfect match)
        n_matched: Number of dimensions that matched
        n_total_prompt: Total dimensions in the prompt

    Returns:
        Confidence in [0, 1]
    """
    if error == float('inf') or n_matched == 0:
        return 0.0

    # Base confidence from error: perfect match → 0.99, 10% error → 0.85
    if error < 0.001:
        base = 0.99
    elif error < 0.01:
        base = 0.95
    elif error < 0.05:
        base = 0.90
    elif error < 0.10:
        base = 0.85
    elif error < 0.20:
        base = 0.70
    else:
        base = max(0.3, 1.0 - error)

    # Bonus for matching more dimensions
    coverage = n_matched / max(n_total_prompt, 1)
    coverage_bonus = coverage * 0.05  # Up to 5% bonus for full coverage

    return min(base + coverage_bonus, 0.99)


def match_prompt_to_component(prompt: str) -> DimensionalMatchResult:
    """
    Match a natural language prompt to a NopSCADlib component using dimensions.

    This is the main entry point. It:
    1. Detects the component family from the prompt
    2. Extracts numeric dimensions
    3. Searches all components in that family
    4. Returns the best match with confidence

    Args:
        prompt: Natural language prompt (anonymized, no model numbers)

    Returns:
        DimensionalMatchResult with best match and alternatives
    """
    result = DimensionalMatchResult(original_prompt=prompt)

    # Step 1: Detect family
    family = _detect_family_from_prompt(prompt)
    if not family:
        return result
    result.detected_family = family

    # Step 2: Extract dimensions from prompt
    prompt_dims = _extract_numbers_with_labels(prompt)
    if not prompt_dims:
        return result

    # Step 3: Get matcher for this family
    matcher = FAMILY_MATCHERS.get(family)
    if not matcher:
        return result

    # Step 4: Search all components in this family
    candidates = _get_components_by_family(family)
    if not candidates:
        return result

    matches = []
    for comp in candidates:
        error, comp_dims = matcher(prompt_dims, comp)
        if error == float('inf'):
            continue

        # Compute confidence
        common_keys = set(prompt_dims.keys()) & set(comp_dims.keys())
        confidence = _error_to_confidence(error, len(common_keys), len(prompt_dims))

        match = DimensionalMatch(
            component_id=comp.get("id", ""),
            type_constant=comp.get("type_constant", ""),
            component_family=family,
            module_function=comp.get("module_function", ""),
            scad_call=comp.get("scad_call", ""),
            confidence=confidence,
            dimension_error=error,
            matched_dimensions=comp_dims,
            prompt_dimensions=prompt_dims,
        )
        matches.append(match)

    # Sort by error (ascending) → best match first
    matches.sort(key=lambda m: m.dimension_error)
    result.matches = matches

    if matches:
        result.best_match = matches[0]
        result.has_match = matches[0].confidence >= 0.70

    return result


